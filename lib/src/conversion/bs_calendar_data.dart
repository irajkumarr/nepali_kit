  static int getDaysInMonth(int year, int month) {
    if (year < NepaliCalendarConstants.minBsYear ||
        year > NepaliCalendarConstants.maxBsYear) {
      throw ConversionOutOfBoundsException(
          'Year out of supported calendar range.',
          value: year,
          minBound: NepaliCalendarConstants.minBsYear,
          maxBound: NepaliCalendarConstants.maxBsYear);
    }
    if (month < 1 || month > 12) {
      throw NepaliDateException(
          'Invalid month index: $month. Must be between 1 and 12.',
          year: year,
          month: month);
    }
    return monthData[year - NepaliCalendarConstants.minBsYear][month - 1];
  }

  static bool isValidBsDate(int year, int month, int day) {
    if (year < NepaliCalendarConstants.minBsYear ||
        year > NepaliCalendarConstants.maxBsYear) {
      return false;
    }
    if (month < 1 || month > 12) {
      return false;
    }
    final maxDays =
        monthData[year - NepaliCalendarConstants.minBsYear][month - 1];
    return day >= 1 && day <= maxDays;
  }
